export type MessageKey = keyof typeof en;

export function t(
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const table = currentLocale() === "zh" ? zh : en;
  const template = table[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : `{${name}}`,
  );
}

export function toolCountLabel(count: number): string {
  const n = formatNumber(count);
  return currentLocale() === "zh"
    ? `${n} 个工具`
    : `${n} ${count === 1 ? "tool" : "tools"}`;
}

export function languageButtonLabel(
  preference: LanguagePreference = currentPreference(),
): string {
  const names =
    currentLocale() === "zh"
      ? (["浏览器", "English", "中文"] as const)
      : (["Browser", "English", "Chinese"] as const);
  const prefix = currentLocale() === "zh" ? "语言" : "Language";
  return `${prefix}: ${names[preference]}`;
}

export function themeButtonLabel(theme: string): string {
  const labels =
    currentLocale() === "zh"
      ? { auto: "自动", light: "浅色", dark: "深色" }
      : { auto: "Auto", light: "Light", dark: "Dark" };
  const prefix = currentLocale() === "zh" ? "主题" : "Theme";
  return `${prefix}: ${labels[theme as keyof typeof labels] ?? theme}`;
}

